#!/usr/bin/env bash
# Builds Vela.apk without Gradle: aapt2 -> javac -> d8 -> zipalign -> apksigner.
# Needs a JDK (17+) and the Android SDK command-line tools (build-tools 34+, platform android-36). See README.md.
set -euo pipefail
cd "$(dirname "$0")"

case "${OSTYPE:-}" in
  msys*|cygwin*)
    if [ "${1:-}" = "--local-config" ]; then exec powershell.exe -NoProfile -ExecutionPolicy Bypass -File ./build.ps1 -UseLocalConfig; fi
    exec powershell.exe -NoProfile -ExecutionPolicy Bypass -File ./build.ps1 ;;
esac

# --- Tools
SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
if [ -z "$SDK" ]; then
  for d in "$HOME/Library/Android/sdk" "$HOME/Android/Sdk" /opt/homebrew/share/android-commandlinetools \
           /usr/local/share/android-commandlinetools /usr/lib/android-sdk; do
    if [ -d "$d/build-tools" ]; then SDK="$d"; break; fi
  done
fi
[ -n "$SDK" ] && [ -d "$SDK/build-tools" ] || { echo "Android SDK not found. Install it and set ANDROID_HOME (see README)."; exit 1; }
BT="$SDK/build-tools/$(ls "$SDK/build-tools" | sort -V | tail -1)"
AJ="$SDK/platforms/android-36/android.jar"
[ -f "${AJ:-}" ] || { echo "Android platform not found. Run: sdkmanager \"platforms;android-36\""; exit 1; }
JAVAC="${JAVA_HOME:+$JAVA_HOME/bin/}javac"
KEYTOOL="${JAVA_HOME:+$JAVA_HOME/bin/}keytool"
command -v "$JAVAC" >/dev/null 2>&1 || { echo "JDK not found. Install JDK 17 and set JAVA_HOME."; exit 1; }

# --- Neutral defaults; private legacy builds must explicitly opt in.
CONFIG_FILE=config.example.properties
if [ "${1:-}" = "--local-config" ]; then CONFIG_FILE=config.properties
elif [ -n "${1:-}" ]; then echo "Usage: ./build.sh [--local-config]" >&2; exit 1; fi
[ -f "$CONFIG_FILE" ] || { echo "Missing $CONFIG_FILE" >&2; exit 1; }
prop() {
  local v
  v="$(grep -E "^[[:space:]]*$1[[:space:]]*=" "$CONFIG_FILE" | tail -1 | cut -d= -f2- || true)"
  v="$(printf '%s' "$v" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' | tr -d '"\\')"
  printf '%s' "${v:-$2}"
}
number() {
  local v; v="$(prop "$1" "$2")"
  [[ "$v" =~ ^-?[0-9]+(\.[0-9]+)?$ ]] || { echo "config.properties: $1 must be a number (got \"$v\")" >&2; exit 1; }
  printf '%s' "$v"
}
LAT="$(number latitude 0)"
LON="$(number longitude 0)"
ASSIST=false; [ "$(prop disable_assistant false)" = "true" ] && ASSIST=true

rm -rf out && mkdir -p out/gen/tv/vela/launcher out/classes
cat > out/gen/tv/vela/launcher/Config.java <<EOF
package tv.vela.launcher;

/** Generated by build.sh from config.properties: edit that file, not this one. */
final class Config {
    private Config() {}

    static final String TMDB_KEY = "$(prop tmdb_key '')";
    static final String TMDB_REGION = "$(prop tmdb_region US)";
    static final String LATITUDE = "$LAT";
    static final String LONGITUDE = "$LON";
    static final String CITY = "$(prop city '')";
    static final String RECOVERY_HOME = "$(prop recovery_home '')";
    static final String LANGUAGE = "$(prop language auto)";
    static final String CURRENCY = "$(prop currency USD)";
    static final String TEMPERATURE = "$(prop temperature auto)";
    static final boolean DISABLE_ASSISTANT = $ASSIST;
    static final boolean DISABLE_APPS = $(prop disable_apps false);
    static final boolean WEATHER_ENABLED = $(prop weather_enabled false);
    static final boolean ISOLATE_RECOVERY_HOME = $(prop isolate_recovery_home false);
}
EOF

# --- Build
"${PYTHON:-python3}" tools/prepare_media3.py
"$BT/aapt2" compile --dir out/media3/res -o out/media3/res.zip
mkdir -p out/lite-assets/licenses
cp -R lite/assets/channel-logos out/lite-assets/
cp lite/assets/channel-logos/CREDITS.txt out/lite-assets/licenses/channel-logos.txt
"$BT/aapt2" compile --dir app/res -o out/res.zip
# Fonts uncompressed: Android reads them straight from the APK.
"$BT/aapt2" link -o out/base.apk -I "$AJ" --manifest app/AndroidManifest.xml --java out/gen out/media3/res.zip out/res.zip --auto-add-overlay \
  --min-sdk-version 26 --target-sdk-version 33 -A app/assets -A out/lite-assets -0 ttf
LIBS=$(find out/media3/libs -name '*.jar' -print | paste -sd: -)
"$JAVAC" -encoding UTF-8 -nowarn -Xlint:-options -source 8 -target 8 -bootclasspath "$AJ:$BT/core-lambda-stubs.jar" -classpath "$AJ:$LIBS" \
  -d out/classes $(find app/src out/gen -name '*.java') $(find lite/src -name '*.java' ! -name LiteSupport.java ! -name Config.java ! -name LiteExportActivity.java ! -name LiteMigrationProvider.java)
"${JAVA_HOME:+$JAVA_HOME/bin/}jar" cf out/classes.jar -C out/classes .
"${JAVA_HOME:+$JAVA_HOME/bin/}java" -cp "$BT/lib/d8.jar" com.android.tools.r8.R8 --release --min-api 26 --lib "$AJ" --lib "$BT/core-lambda-stubs.jar" --pg-conf out/media3/rules.pro --output out out/classes.jar $(find out/media3/libs -name '*.jar')
(cd out && zip -qj base.apk classes*.dex)
"$BT/zipalign" -f -p 4 out/base.apk out/aligned.apk

# --- Sign with your own key (created once; updates need the same key, so keep vela.keystore)
if [ ! -f vela.keystore ]; then
  "$KEYTOOL" -genkeypair -keystore vela.keystore -alias vela -keyalg RSA -keysize 2048 -validity 20000 \
    -storepass vela-local -keypass vela-local -dname "CN=Vela" >/dev/null 2>&1
fi
"$BT/apksigner" sign --ks vela.keystore --ks-pass pass:vela-local --key-pass pass:vela-local --out Vela.apk out/aligned.apk
echo "Built Vela.apk ($(du -h Vela.apk | cut -f1)). Install: adb install -r Vela.apk"
