# Native Windows build, using only a JDK and the Android SDK.
param([string]$SdkPath = '', [string]$JdkPath = '', [switch]$UseLocalConfig, [string]$PythonPath = 'python')
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
Set-Location -LiteralPath $PSScriptRoot

if (!$SdkPath) { $SdkPath = $env:ANDROID_HOME }
if (!$SdkPath) { $SdkPath = $env:ANDROID_SDK_ROOT }
if (!$SdkPath) { $SdkPath = Join-Path $env:LOCALAPPDATA 'Android\Sdk' }
$SdkPath = (Resolve-Path -LiteralPath $SdkPath).Path
if (!$JdkPath) { $JdkPath = $env:JAVA_HOME }
if (!$JdkPath) {
    $compiler = Get-Command javac.exe -ErrorAction SilentlyContinue
    if ($compiler) { $JdkPath = Split-Path (Split-Path $compiler.Source -Parent) -Parent }
}
if (!$JdkPath -or !(Test-Path -LiteralPath (Join-Path $JdkPath 'bin\javac.exe'))) {
    throw 'JDK 17+ not found. Set JAVA_HOME or pass -JdkPath.'
}
$env:JAVA_HOME = (Resolve-Path -LiteralPath $JdkPath).Path
$buildTools = Get-ChildItem -LiteralPath (Join-Path $SdkPath 'build-tools') -Directory |
    Where-Object { $_.Name -match '^\d+\.\d+\.\d+$' } | Sort-Object { [version]$_.Name } | Select-Object -Last 1
if (!$buildTools) { throw 'Install Android SDK build-tools 34 or newer.' }
$bt = $buildTools.FullName
$androidJar = Join-Path $SdkPath 'platforms\android-36\android.jar'
if (!(Test-Path -LiteralPath $androidJar)) { throw 'Install SDK platform android-36.' }

function Run-Native([string]$Command, [string[]]$Arguments) {
    & $Command @Arguments
    if ($LASTEXITCODE -ne 0) { throw "Build command failed: $([IO.Path]::GetFileName($Command)) ($LASTEXITCODE)" }
}
$utf8 = New-Object System.Text.UTF8Encoding($false)
$configFile = if ($UseLocalConfig) { 'config.properties' } else { 'config.example.properties' }
if (!(Test-Path -LiteralPath $configFile)) { throw "Configuration file not found: $configFile" }
$properties = @{}
foreach ($line in [IO.File]::ReadAllLines((Join-Path $PSScriptRoot $configFile), $utf8)) {
    if ($line -match '^\s*([^#!\s=]+)\s*=(.*)$') { $properties[$Matches[1]] = $Matches[2].Trim() }
}
function Property([string]$Key, [string]$Default) {
    if ($properties.ContainsKey($Key) -and $properties[$Key] -ne '') { return $properties[$Key] }
    return $Default
}
function Java-String([string]$Value) {
    return '"' + $Value.Replace('\', '\\').Replace('"', '\"').Replace("`r", '\r').Replace("`n", '\n') + '"'
}
function Boolean-Property([string]$Key, [string]$Default) {
    $value = (Property $Key $Default).ToLowerInvariant()
    if ($value -ne 'true' -and $value -ne 'false') { throw "config.properties: $Key must be true or false" }
    return $value
}
foreach ($coordinate in @('latitude', 'longitude')) {
    $fallback = '0'
    $value = Property $coordinate $fallback
    if ($value -notmatch '^-?\d+(\.\d+)?$') { throw "config.properties: $coordinate must be a decimal number" }
    $limit = if ($coordinate -eq 'latitude') { 90 } else { 180 }
    if ([math]::Abs([double]::Parse($value, [Globalization.CultureInfo]::InvariantCulture)) -gt $limit) {
        throw "config.properties: $coordinate is outside its valid range"
    }
}
$outPath = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot 'out'))
if ($outPath -ne (Join-Path $PSScriptRoot 'out')) { throw 'Unexpected output directory' }
if (Test-Path -LiteralPath $outPath) { Remove-Item -LiteralPath $outPath -Recurse -Force }
New-Item -ItemType Directory -Path 'out\gen\tv\vela\launcher','out\classes','out\lite-assets','out\lite-assets\licenses' -Force | Out-Null
$fields = [ordered]@{
    TMDB_KEY = (Property 'tmdb_key' ''); TMDB_REGION = (Property 'tmdb_region' 'US')
    LATITUDE = (Property 'latitude' '0'); LONGITUDE = (Property 'longitude' '0')
    CITY = (Property 'city' ''); LANGUAGE = (Property 'language' 'auto')
    RECOVERY_HOME = (Property 'recovery_home' '')
    CURRENCY = (Property 'currency' 'USD'); TEMPERATURE = (Property 'temperature' 'auto')
}
$generated = @('package tv.vela.launcher;', '/** Generated by build.ps1. */', 'final class Config {', '    private Config() {}')
foreach ($field in $fields.GetEnumerator()) { $generated += '    static final String ' + $field.Key + ' = ' + (Java-String $field.Value) + ';' }
foreach ($field in @(@('DISABLE_ASSISTANT','disable_assistant'), @('DISABLE_APPS','disable_apps'), @('WEATHER_ENABLED','weather_enabled'), @('ISOLATE_RECOVERY_HOME','isolate_recovery_home'))) {
    $generated += '    static final boolean ' + $field[0] + ' = ' + (Boolean-Property $field[1] 'false') + ';'
}
$generated += '}'
[IO.File]::WriteAllLines((Join-Path $outPath 'gen\tv\vela\launcher\Config.java'), $generated, $utf8)

Copy-Item -LiteralPath 'lite/assets/channel-logos' -Destination 'out/lite-assets' -Recurse -Force
Copy-Item -LiteralPath 'lite/assets/channel-logos/CREDITS.txt' -Destination 'out/lite-assets/licenses/channel-logos.txt'
Run-Native $PythonPath @('tools/prepare_media3.py')
Run-Native (Join-Path $bt 'aapt2.exe') @('compile','--dir','out/media3/res','-o','out/media3/res.zip')
Run-Native (Join-Path $bt 'aapt2.exe') @('compile','--dir','app/res','-o','out/res.zip')
Run-Native (Join-Path $bt 'aapt2.exe') @('link','-o','out/base.apk','-I',$androidJar,'--manifest','app/AndroidManifest.xml',
    '--java','out/gen','out/media3/res.zip','out/res.zip','--auto-add-overlay','--min-sdk-version','26','--target-sdk-version','33','-A','app/assets','-A','out/lite-assets','-0','ttf')
$liteControllers = @(Get-ChildItem -LiteralPath 'lite/src/tv/vela/launcher' -Filter '*.java' | Where-Object { $_.Name -notin @('LiteSupport.java','Config.java','LiteExportActivity.java','LiteMigrationProvider.java') } | ForEach-Object { '"' + $_.FullName.Replace('\','/') + '"' })
$sources = @(Get-ChildItem -LiteralPath 'app\src','out\gen' -Filter '*.java' -Recurse | ForEach-Object { '"' + $_.FullName.Replace('\','/') + '"' })
$sources += $liteControllers
[IO.File]::WriteAllLines((Join-Path $outPath 'sources.txt'), $sources, $utf8)
Run-Native (Join-Path $env:JAVA_HOME 'bin\javac.exe') @('-encoding','UTF-8','-nowarn','-Xlint:-options','-source','8','-target','8',
    '-bootclasspath',($androidJar + ';' + (Join-Path $bt 'core-lambda-stubs.jar')),'-classpath',($androidJar + ';' + ((Get-ChildItem -LiteralPath 'out/media3/libs' -Filter '*.jar' | ForEach-Object { $_.FullName }) -join ';')),'-d','out/classes','@out/sources.txt')
Run-Native (Join-Path $env:JAVA_HOME 'bin\jar.exe') @('cf','out/classes.jar','-C','out/classes','.')
$r8args = @('-cp',(Join-Path $bt 'lib/d8.jar'),'com.android.tools.r8.R8','--release','--min-api','26','--lib',$androidJar,'--lib',(Join-Path $bt 'core-lambda-stubs.jar'),'--pg-conf','out/media3/rules.pro','--output','out','out/classes.jar') + @(Get-ChildItem -LiteralPath 'out/media3/libs' -Filter '*.jar' | ForEach-Object { $_.FullName })
Run-Native (Join-Path $env:JAVA_HOME 'bin/java.exe') $r8args
# Windows aapt2 can emit backslashes in asset names; Android requires ZIP paths with '/'.
Add-Type -AssemblyName System.IO.Compression.FileSystem
[IO.Compression.ZipFile]::ExtractToDirectory((Join-Path $outPath 'base.apk'), (Join-Path $outPath 'package'))
Get-ChildItem -LiteralPath $outPath -Filter 'classes*.dex' | Copy-Item -Destination (Join-Path $outPath 'package')
# Store every entry: resources.arsc and fonts must remain uncompressed.
Run-Native (Join-Path $env:JAVA_HOME 'bin\jar.exe') @('c0Mf','out/normalized.apk','-C','out/package','.')
Run-Native (Join-Path $bt 'zipalign.exe') @('-f','-p','4','out/normalized.apk','out/aligned.apk')
if (!(Test-Path -LiteralPath 'vela.keystore')) {
    Run-Native (Join-Path $env:JAVA_HOME 'bin\keytool.exe') @('-genkeypair','-keystore','vela.keystore','-alias','vela',
        '-keyalg','RSA','-keysize','2048','-validity','20000','-storepass','vela-local','-keypass','vela-local','-dname','CN=Vela')
}
Run-Native (Join-Path $bt 'apksigner.bat') @('sign','--ks','vela.keystore','--ks-pass','pass:vela-local','--key-pass','pass:vela-local',
    '--out','Vela.apk','out/aligned.apk')
Run-Native (Join-Path $bt 'apksigner.bat') @('verify','--verbose','Vela.apk')
Write-Output 'Built Vela.apk'
